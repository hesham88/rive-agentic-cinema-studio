/**
 * Every property key the Rive runtime understands, and how each is encoded.
 *
 * GENERATED from the 371 core definitions in `rive-runtime/dev/defs`.
 * Do not hand-edit; regenerate when the runtime version changes.
 *
 * Why a decoder needs this at all: `readRuntimeObject` resolves a property key
 * from the runtime's own compiled-in registry FIRST, and only falls back to the
 * file's table of contents. A real editor export therefore legitimately omits
 * well-known keys from its ToC — so a decoder that trusts the ToC alone
 * desynchronises the byte stream the moment it meets one, and every object
 * after that point is garbage.
 *
 * Three subtleties are baked in here:
 *
 *   - **`typeRuntime` overrides `type`.** The generator does
 *     `FieldType.find(typeRuntime) ?? FieldType.find(type)`. Every runtime
 *     `List<Id>` declares `typeRuntime: "Bytes"`, so it is length-prefixed and
 *     shares the string field id — not a sequence of varints as the name
 *     suggests.
 *   - **Alternate keys are included.** `Node.x` also answers to key 9
 *     (`xArtboard`) and `Node.y` to key 10. Files published before that rename
 *     still use them, so omitting them makes every pre-7.3 file undecodable.
 *   - **Editor-only properties are excluded.** Anything marked
 *     `runtime: false` never appears on the wire.
 *
 * 620 keys: 344 uint-family, 37 length-prefixed,
 * 232 float32, 7 color.
 */

